"""Small, inspectable evidence-decision domain for the RSI demonstration.

This is a *synthetic benchmark*, not an EFMW-specific physical model or an
implementation of general intelligence. The labels are generated by an oracle.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from enum import Enum
import random
from typing import Any


class Label(str, Enum):
    SUPPORTED = "SUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    UNRESOLVED = "UNRESOLVED"


@dataclass(frozen=True)
class Case:
    case_id: str
    supports: int
    contradictions: int
    provenance_verified: bool
    bridge_verified: bool
    truth: str

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class Policy:
    support_threshold: int = 2
    contradiction_threshold: int = 2
    require_provenance: bool = False
    require_bridge: bool = False
    conflict_handling: str = "prefer_support"

    def validate(self) -> None:
        if not 1 <= self.support_threshold <= 3:
            raise ValueError("support_threshold must be in 1..3")
        if not 1 <= self.contradiction_threshold <= 3:
            raise ValueError("contradiction_threshold must be in 1..3")
        if self.conflict_handling not in {
            "abstain", "prefer_support", "prefer_contradiction"
        }:
            raise ValueError("unknown conflict_handling")
        if type(self.require_provenance) is not bool or type(self.require_bridge) is not bool:
            raise ValueError("require_provenance/require_bridge must be booleans")

    @classmethod
    def from_dict(cls, values: dict[str, Any]) -> "Policy":
        expected = set(cls.__dataclass_fields__)
        if set(values) != expected:
            raise ValueError(f"policy keys must be {sorted(expected)}")
        obj = cls(**values)
        obj.validate()
        return obj

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


def oracle(supports: int, contradictions: int, provenance: bool, bridge: bool) -> Label:
    """Frozen synthetic labeling rule; a constructed target, not discovered truth."""
    if not provenance or not bridge:
        return Label.UNRESOLVED
    if supports > 0 and contradictions > 0:
        return Label.UNRESOLVED
    if supports > 0:
        return Label.SUPPORTED
    if contradictions > 0:
        return Label.CONTRADICTED
    return Label.UNRESOLVED


def predict(policy: Policy, case: Case) -> tuple[str, str]:
    """Return decision and traceable reason."""
    if policy.require_provenance and not case.provenance_verified:
        return Label.UNRESOLVED.value, "missing provenance"
    if policy.require_bridge and not case.bridge_verified:
        return Label.UNRESOLVED.value, "missing bridge"
    yes = case.supports >= policy.support_threshold
    no = case.contradictions >= policy.contradiction_threshold
    if yes and no:
        if policy.conflict_handling == "prefer_support":
            return Label.SUPPORTED.value, "conflicting evidence: prefer support"
        if policy.conflict_handling == "prefer_contradiction":
            return Label.CONTRADICTED.value, "conflicting evidence: prefer contradiction"
        return Label.UNRESOLVED.value, "conflicting evidence: abstain"
    if yes:
        return Label.SUPPORTED.value, "support threshold reached"
    if no:
        return Label.CONTRADICTED.value, "contradiction threshold reached"
    return Label.UNRESOLVED.value, "insufficient evidence"


def generate_cases(size: int, seed: int, partition: str, distribution: str) -> list[Case]:
    if size <= 0:
        raise ValueError("size must be positive")
    if distribution not in {"uniform", "stress"}:
        raise ValueError("distribution must be uniform or stress")
    rng = random.Random(seed)
    cases: list[Case] = []
    for i in range(size):
        if distribution == "uniform":
            s, c = rng.randrange(4), rng.randrange(4)
            provenance, bridge = rng.random() < 0.8, rng.random() < 0.75
        else:
            # Deliberate distribution shift; no new label rule is introduced.
            s, c = rng.choice([0, 0, 1, 1, 2, 3]), rng.choice([0, 1, 1, 2, 3])
            provenance, bridge = rng.random() < 0.55, rng.random() < 0.6
        truth = oracle(s, c, provenance, bridge).value
        cases.append(Case(f"{partition}-{i:05d}-{rng.getrandbits(48):012x}",
                          s, c, provenance, bridge, truth))
    return cases


def score(policy: Policy, cases: list[Case]) -> dict[str, Any]:
    if not cases:
        raise ValueError("cannot score empty cases")
    predictions = [predict(policy, item)[0] for item in cases]
    correct = sum(p == case.truth for p, case in zip(predictions, cases))
    false_assertions = sum(
        p != Label.UNRESOLVED.value and p != case.truth
        for p, case in zip(predictions, cases)
    )
    asserted = sum(p != Label.UNRESOLVED.value for p in predictions)
    matrix = {
        actual.value: {pred.value: 0 for pred in Label}
        for actual in Label
    }
    for case, p in zip(cases, predictions):
        matrix[case.truth][p] += 1
    return {
        "n": len(cases),
        "correct": correct,
        "accuracy": correct / len(cases),
        "false_assertions": false_assertions,
        "false_assertion_rate": false_assertions / len(cases),
        "coverage": asserted / len(cases),
        "confusion": matrix,
    }


def random_policy(rng: random.Random) -> Policy:
    return Policy(
        support_threshold=rng.randint(1, 3),
        contradiction_threshold=rng.randint(1, 3),
        require_provenance=bool(rng.randrange(2)),
        require_bridge=bool(rng.randrange(2)),
        conflict_handling=rng.choice(["abstain", "prefer_support", "prefer_contradiction"]),
    )


def mutate(policy: Policy, rng: random.Random) -> Policy:
    options: dict[str, list[Any]] = {
        "support_threshold": [1, 2, 3],
        "contradiction_threshold": [1, 2, 3],
        "require_provenance": [False, True],
        "require_bridge": [False, True],
        "conflict_handling": ["abstain", "prefer_support", "prefer_contradiction"],
    }
    gene = rng.choice(list(options))
    values = policy.as_dict()
    values[gene] = rng.choice([v for v in options[gene] if v != values[gene]])
    return Policy.from_dict(values)
